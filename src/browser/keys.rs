//! Browser key combinations translated to CDP `Input.dispatchKeyEvent`.
//!
//! The desktop `keys` module talks to the OS; this one talks to a page. It
//! covers the combinations an agent needs (Enter, Tab, Escape, arrows,
//! Backspace, Delete, Home/End/Page keys, F1–F12, letters, digits, and the
//! usual punctuation) with `cmd`/`ctrl`/`alt`/`shift` modifiers.

#![cfg(feature = "cdp")]

use chromiumoxide::cdp::browser_protocol::input::{DispatchKeyEventParams, DispatchKeyEventType};

use crate::error::ComputerError;

/// One key event pair.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyStroke {
    /// DOM `key` value.
    pub key: String,
    /// DOM `code` value when known.
    pub code: Option<String>,
    /// Windows virtual key code.
    pub virtual_key_code: i64,
    /// Text generated by the key, when it is a printable character.
    pub text: Option<String>,
    /// CDP modifier bit field.
    pub modifiers: i64,
}

/// Parse `cmd+a`, `ctrl+shift+Tab`, `Enter`, or `ArrowDown` into one stroke.
pub fn parse(combo: &str) -> Result<KeyStroke, ComputerError> {
    let text = combo.trim();
    if text.is_empty() {
        return Err(ComputerError::InvalidArguments(
            "press needs a key combination".into(),
        ));
    }
    let mut modifiers: i64 = 0;
    let mut key_token: Option<String> = None;
    for part in text.split('+') {
        let token = part.trim();
        if token.is_empty() {
            continue;
        }
        match token.to_ascii_lowercase().as_str() {
            "cmd" | "command" | "meta" | "super" => modifiers |= 4,
            "ctrl" | "control" => modifiers |= 2,
            "alt" | "option" => modifiers |= 1,
            "shift" => modifiers |= 8,
            _ => {
                if key_token.is_some() {
                    return Err(ComputerError::InvalidArguments(format!(
                        "press accepts one key plus modifiers (got {combo})"
                    )));
                }
                key_token = Some(token.to_string());
            }
        }
    }
    let key_token = key_token.ok_or_else(|| {
        ComputerError::InvalidArguments(format!(
            "press needs a key after the modifiers (got {combo})"
        ))
    })?;
    let stroke = stroke_for(&key_token, modifiers)?;
    Ok(stroke)
}

fn stroke_for(token: &str, modifiers: i64) -> Result<KeyStroke, ComputerError> {
    let lower = token.to_ascii_lowercase();
    let (key, code, vk): (String, Option<String>, i64) = match lower.as_str() {
        "enter" | "return" => ("Enter".into(), Some("Enter".into()), 13),
        "tab" => ("Tab".into(), Some("Tab".into()), 9),
        "esc" | "escape" => ("Escape".into(), Some("Escape".into()), 27),
        "backspace" => ("Backspace".into(), Some("Backspace".into()), 8),
        "delete" | "del" => ("Delete".into(), Some("Delete".into()), 46),
        "space" | "spacebar" => (" ".into(), Some("Space".into()), 32),
        "arrowup" | "up" => ("ArrowUp".into(), Some("ArrowUp".into()), 38),
        "arrowdown" | "down" => ("ArrowDown".into(), Some("ArrowDown".into()), 40),
        "arrowleft" | "left" => ("ArrowLeft".into(), Some("ArrowLeft".into()), 37),
        "arrowright" | "right" => ("ArrowRight".into(), Some("ArrowRight".into()), 39),
        "home" => ("Home".into(), Some("Home".into()), 36),
        "end" => ("End".into(), Some("End".into()), 35),
        "pageup" | "page_up" => ("PageUp".into(), Some("PageUp".into()), 33),
        "pagedown" | "page_down" => ("PageDown".into(), Some("PageDown".into()), 34),
        "insert" => ("Insert".into(), Some("Insert".into()), 45),
        "capslock" | "caps_lock" => ("CapsLock".into(), Some("CapsLock".into()), 20),
        _ if lower.starts_with('f') && lower[1..].parse::<u8>().is_ok() => {
            let number: u8 = lower[1..]
                .parse()
                .map_err(|_| ComputerError::InvalidArguments(format!("unknown key: {token}")))?;
            if !(1..=12).contains(&number) {
                return Err(ComputerError::InvalidArguments(format!(
                    "function keys are f1..f12 (got {token})"
                )));
            }
            let vk = 111 + number as i64;
            (format!("F{number}"), Some(format!("F{number}")), vk)
        }
        _ => {
            let mut chars = token.chars();
            let first = chars
                .next()
                .ok_or_else(|| ComputerError::InvalidArguments(format!("unknown key: {token}")))?;
            if chars.next().is_some() {
                return Err(ComputerError::InvalidArguments(format!(
                    "unknown key: {token}. Use a named key (Enter, Tab, ArrowDown) or one character."
                )));
            }
            if first.is_ascii_alphabetic() {
                let upper = first.to_ascii_uppercase();
                let vk = upper as i64;
                (upper.to_string(), Some(format!("Key{upper}")), vk)
            } else if first.is_ascii_digit() {
                (
                    first.to_string(),
                    Some(format!("Digit{first}")),
                    first as i64,
                )
            } else {
                let vk = first as i64;
                (first.to_string(), None, vk)
            }
        }
    };
    let shifted = modifiers & 8 != 0;
    let command_like = modifiers & (2 | 4) != 0;
    let text = if command_like {
        None
    } else if key == "Enter" {
        Some("\r".into())
    } else if key == "Tab" {
        Some("\t".into())
    } else if key.chars().count() == 1 {
        let ch = if shifted {
            key.to_uppercase()
        } else {
            key.to_lowercase()
        };
        Some(ch)
    } else {
        None
    };
    Ok(KeyStroke {
        key,
        code,
        virtual_key_code: vk,
        text,
        modifiers,
    })
}

/// Dispatch one combination: keyDown followed by keyUp.
pub async fn dispatch(page: &chromiumoxide::Page, combo: &str) -> Result<KeyStroke, ComputerError> {
    let stroke = parse(combo)?;
    dispatch_stroke(page, &stroke).await?;
    Ok(stroke)
}

async fn dispatch_stroke(
    page: &chromiumoxide::Page,
    stroke: &KeyStroke,
) -> Result<(), ComputerError> {
    let mut down = DispatchKeyEventParams::builder()
        .r#type(DispatchKeyEventType::KeyDown)
        .key(stroke.key.clone())
        .windows_virtual_key_code(stroke.virtual_key_code)
        .native_virtual_key_code(stroke.virtual_key_code)
        .modifiers(stroke.modifiers);
    if let Some(code) = &stroke.code {
        down = down.code(code.clone());
    }
    if let Some(text) = &stroke.text {
        down = down.text(text.clone());
    }
    let down = down
        .build()
        .map_err(|error| ComputerError::ExecutionFailed(format!("key event: {error}")))?;
    page.execute(down)
        .await
        .map_err(|error| ComputerError::ExecutionFailed(format!("key down: {error}")))?;

    let mut up = DispatchKeyEventParams::builder()
        .r#type(DispatchKeyEventType::KeyUp)
        .key(stroke.key.clone())
        .windows_virtual_key_code(stroke.virtual_key_code)
        .native_virtual_key_code(stroke.virtual_key_code)
        .modifiers(stroke.modifiers);
    if let Some(code) = &stroke.code {
        up = up.code(code.clone());
    }
    let up = up
        .build()
        .map_err(|error| ComputerError::ExecutionFailed(format!("key event: {error}")))?;
    page.execute(up)
        .await
        .map_err(|error| ComputerError::ExecutionFailed(format!("key up: {error}")))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn named_keys_and_function_keys_parse() {
        let named = [
            ("enter", "Enter", 13),
            ("tab", "Tab", 9),
            ("esc", "Escape", 27),
            ("backspace", "Backspace", 8),
            ("delete", "Delete", 46),
            ("space", " ", 32),
            ("up", "ArrowUp", 38),
            ("down", "ArrowDown", 40),
            ("left", "ArrowLeft", 37),
            ("right", "ArrowRight", 39),
            ("home", "Home", 36),
            ("end", "End", 35),
            ("pageup", "PageUp", 33),
            ("pagedown", "PageDown", 34),
            ("insert", "Insert", 45),
            ("capslock", "CapsLock", 20),
        ];
        for (token, key, vk) in named {
            let stroke = parse(token).unwrap_or_else(|error| panic!("{token}: {error}"));
            assert_eq!(stroke.key, key, "{token}");
            assert_eq!(stroke.virtual_key_code, vk, "{token}");
        }
        for number in 1..=12 {
            let stroke = parse(&format!("f{number}")).unwrap();
            assert_eq!(stroke.key, format!("F{number}"));
            assert_eq!(stroke.virtual_key_code, 111 + i64::from(number));
        }
        assert!(parse("f13").is_err());
        assert!(parse("f0").is_err());
        assert!(parse("ctrl+shift+tab").is_ok());
    }

    #[test]
    fn named_keys_and_modifiers_parse() {
        let stroke = parse("ctrl+shift+Tab").unwrap();
        assert_eq!(stroke.key, "Tab");
        assert_eq!(stroke.modifiers, 2 | 8);
        let stroke = parse("Enter").unwrap();
        assert_eq!(stroke.key, "Enter");
        assert_eq!(stroke.virtual_key_code, 13);
        let stroke = parse("a").unwrap();
        assert_eq!(stroke.key, "A");
        assert_eq!(stroke.code.as_deref(), Some("KeyA"));
        assert_eq!(stroke.text.as_deref(), Some("a"));
    }

    #[test]
    fn cmd_shortcuts_have_no_text() {
        let stroke = parse("cmd+a").unwrap();
        assert_eq!(stroke.modifiers, 4);
        assert_eq!(stroke.text, None);
    }

    #[test]
    fn unknown_multi_character_key_is_rejected() {
        assert!(parse("Banana").is_err());
        assert!(parse("ctrl+").is_err());
    }
}
